def topic_emoji(title: str) -> str:
    text = title.lower()
    if any(word in text for word in ("чист", "флуд", "мусор", "уборк")):
        return "🧹"
    if any(word in text for word in ("хотэнд", "хотенд", "сопл", "нагрев", "температур")):
        return "🔥"
    if any(word in text for word in ("настрой", "скорост", "калибр", "слой", "слайсер")):
        return "⚙️"
    if any(word in text for word in ("ошиб", "код", "не работает")):
        return "🚨"
    if any(word in text for word in ("филамент", "пластик", "катуш")):
        return "🧵"
    return "💬"


def _format_date(day: str) -> str:
    _year, month, number = (int(part) for part in day.split("-"))
    return f"{number} {MONTH_NAMES[month - 1]}"


def _phrase_pair(*, day: str, scope_key: str) -> tuple[str, str]:
    digest = hashlib.sha256(f"{day}|{scope_key}".encode("utf-8")).digest()
    return OPENING_PHRASES[digest[0] % 50], CLOSING_PHRASES[digest[1] % 50]


def format_daily_summary(
    *, day: str, scope_label: str, scope_key: str, total_incoming: int, topics: list[tuple[str, int]]
) -> str:
    """Формирует одинаковую сводку для Telegram-команды и Mini App."""
    opening, closing = _phrase_pair(day=day, scope_key=scope_key)
    lines = [
        opening.format(scope=scope_label, date=_format_date(day)),
        "",
        f"Всего было написано {total_incoming} сообщений",
        "",
    ]
    if topics:
        lines.extend(f"{topic_emoji(title)} {title} ({count} сообщений)" for title, count in topics)
    else:
        lines.append("За этот день бот не выделил отдельных тем.")
    lines.extend(["", closing])
    return "\n".join(lines)
