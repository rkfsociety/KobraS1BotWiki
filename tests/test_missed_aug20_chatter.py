@pytest.mark.parametrize("text", CHATTER)
def test_aug20_chatter_is_filtered(text: str) -> None:
    assert _is_conversational_chatter(text), text


@pytest.mark.parametrize("text", REAL_QUESTIONS)
def test_aug20_real_questions_pass(text: str) -> None:
    assert not _is_missed_aug20_thread_noise(text), text
    assert not _is_conversational_chatter(text), text


def test_resin_printer_topics_are_offtopic() -> None:
    """Группа про FDM: вопросы по фотополимерникам бот не подхватывает."""
    assert _is_missed_aug20_thread_noise("купил аникубик моно 4, что дальше?")
    assert _is_missed_aug20_thread_noise("mono 4 ultra привезли сегодня")


def test_short_fragment_question_needs_no_answer() -> None:
    assert _is_missed_aug20_thread_noise("Кайму ?")
    assert _is_missed_aug20_thread_noise("скока рисует?")
    # длинный вопрос обрывком не считается
    assert not _is_missed_aug20_thread_noise(
        "Кайму ставить обязательно при печати высоких деталей из PETG?"
    )
    # код ошибки в коротком сообщении — не обрывок
    assert not _is_missed_aug20_thread_noise("ошибка 11518?")
